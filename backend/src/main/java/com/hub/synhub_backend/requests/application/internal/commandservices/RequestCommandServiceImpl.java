package com.hub.synhub_backend.requests.application.internal.commandservices;

import com.hub.synhub_backend.requests.domain.exceptions.*;
import com.hub.synhub_backend.requests.domain.model.aggregates.Request;
import com.hub.synhub_backend.requests.domain.model.commands.CreateRequestCommand;
import com.hub.synhub_backend.requests.domain.model.commands.DeleteRequestCommand;
import com.hub.synhub_backend.requests.domain.model.commands.UpdateRequestCommand;
import com.hub.synhub_backend.requests.domain.model.valueobjects.RequestStatus;
import com.hub.synhub_backend.requests.domain.model.valueobjects.RequestType;
import com.hub.synhub_backend.requests.domain.services.RequestCommandService;
import com.hub.synhub_backend.requests.infrastructure.persistence.jpa.repositories.RequestRepository;
import com.hub.synhub_backend.shared.interfaces.rest.exceptions.ResourceNotFoundException;
import com.hub.synhub_backend.tasks.domain.model.valueobjects.TaskStatus;
import com.hub.synhub_backend.tasks.interfaces.acl.TasksContextFacade;
import java.util.Optional;
import org.springframework.security.access.AccessDeniedException;
import org.springframework.stereotype.Service;
import org.springframework.transaction.annotation.Transactional;

@Service
@Transactional
public class RequestCommandServiceImpl implements RequestCommandService {

    private final RequestRepository requestRepository;
    private final TasksContextFacade tasksContextFacade;

    public RequestCommandServiceImpl(RequestRepository requestRepository, TasksContextFacade tasksContextFacade) {
        this.requestRepository = requestRepository;
        this.tasksContextFacade = tasksContextFacade;
    }

    @Override
    public Long handle(CreateRequestCommand command) {
        RequestType requestType;
        try {
            requestType = RequestType.fromString(command.requestType());
        } catch (IllegalArgumentException e) {
            throw new IllegalArgumentException("Invalid request type");
        }

        var task = this.tasksContextFacade
                .getTaskById(command.taskId())
                .orElseThrow(
                        () -> new ResourceNotFoundException("Task with id " + command.taskId() + " does not exist"));

        if (requestRepository.existsByTask_IdAndRequestStatus(command.taskId(), RequestStatus.PENDING))
            throw new PendingRequestAlreadyExistsException(command.taskId());

        // requesterId null = la genera el sistema (vencimiento automático): sin reglas de usuario.
        if (command.requesterId() != null) {
            if (requestType == RequestType.EXPIRED)
                throw new IllegalArgumentException("Requests of type EXPIRED are generated by the system");
            if (!task.getProfile().getUser().getId().equals(command.requesterId()))
                throw new AccessDeniedException("Only the member assigned to the task can create requests for it");
            // El vencimiento automático (sin solicitante) sigue registrándose en un grupo bloqueado.
            task.getProfile().getGroup().ensureNotLocked();
            if (requestType == RequestType.SUBMISSION) {
                // Entregar marca la tarea como completada: el integrante no cambia estados por su cuenta.
                // COMPLETED también vale (la dejó así el líder) para no dejarla sin forma de enviarse.
                if (task.getStatus() != TaskStatus.IN_PROGRESS && task.getStatus() != TaskStatus.COMPLETED)
                    throw new TaskWithIncorrectStatusException(
                            "A submission can only be created for an IN_PROGRESS or COMPLETED task, the task is "
                                    + task.getStatus());
                if (task.getStatus() == TaskStatus.IN_PROGRESS)
                    this.tasksContextFacade.completeForSubmission(command.taskId());
            }
            if (requestType == RequestType.MODIFICATION) {
                if (command.description() == null || command.description().isBlank())
                    throw new IllegalArgumentException("A modification request needs a comment");
                if (task.getStatus() != TaskStatus.IN_PROGRESS)
                    throw new TaskWithIncorrectStatusException(
                            "A modification request can only be created for a IN_PROGRESS task, the task is "
                                    + task.getStatus());
                // Pedir una modificación detiene la tarea (y su reloj) hasta que el líder la edite.
                this.tasksContextFacade.putOnHoldForModification(command.taskId());
            }
        }

        var request = new Request(command);
        request.setTask(task);
        this.requestRepository.save(request);
        return request.getId();
    }

    @Override
    @Transactional
    public Optional<Request> handle(UpdateRequestCommand command) {
        var request = this.requestRepository
                .findById(command.requestId())
                .orElseThrow(() ->
                        new ResourceNotFoundException("Request with id " + command.requestId() + " does not exist"));
        var task = request.getTask();
        if (!task.getProfile().getGroup().getLeader().getId().equals(command.requesterId()))
            throw new AccessDeniedException("Only the leader of the group can review requests");
        task.getProfile().getGroup().ensureNotLocked();

        var newStatus = RequestStatus.fromString(command.requestStatus());
        if (newStatus == RequestStatus.PENDING)
            throw new IllegalArgumentException("A request can only be reviewed as APPROVED or REJECTED");
        // El vencimiento tampoco se rechaza: solo se reanuda la tarea (eso cierra el aviso).
        if (RequestType.EXPIRED.name().equals(request.getRequestType()) && newStatus == RequestStatus.REJECTED)
            throw new ExpiredRequestCannotBeRejectedException(request.getId());
        // Una modificación se aprueba editando la tarea (eso cierra la solicitud); desde aquí solo se puede denegar.
        if (RequestType.MODIFICATION.name().equals(request.getRequestType()) && newStatus == RequestStatus.APPROVED)
            throw new ModificationResolvedByEditingException(request.getId());
        if (!RequestStatus.PENDING.name().equals(request.getRequestStatus()))
            throw new RequestAlreadyReviewedException(request.getId(), request.getRequestStatus());

        // SUBMISSION mueve la tarea según la revisión; denegar una MODIFICATION la reanuda; EXPIRED solo se cierra.
        if (RequestType.MODIFICATION.name().equals(request.getRequestType())) {
            this.tasksContextFacade.resumeAfterModificationDenied(task.getId());
        } else if (RequestType.SUBMISSION.name().equals(request.getRequestType())) {
            if (newStatus == RequestStatus.APPROVED) {
                if (task.getStatus() != TaskStatus.COMPLETED)
                    throw new TaskWithIncorrectStatusException(
                            "Only a COMPLETED task can be approved, the task is " + task.getStatus());
                this.tasksContextFacade.applySubmissionReview(task.getId(), true);
            } else if (task.getStatus() == TaskStatus.COMPLETED) {
                // Si el miembro ya la sacó de COMPLETED, rechazar solo cierra la request.
                this.tasksContextFacade.applySubmissionReview(task.getId(), false);
            }
        }

        request.updateRequestStatus(newStatus.name());
        return Optional.of(this.requestRepository.save(request));
    }

    @Override
    @Transactional
    public void handle(DeleteRequestCommand command) {
        var request = this.requestRepository
                .findById(command.requestId())
                .orElseThrow(() ->
                        new ResourceNotFoundException("Request with id " + command.requestId() + " does not exist"));
        var task = request.getTask();
        var isLeader = task.getProfile().getGroup().getLeader().getId().equals(command.requesterId());
        var isOwnPendingRequest = task.getProfile().getUser().getId().equals(command.requesterId())
                && RequestStatus.PENDING.name().equals(request.getRequestStatus())
                && !RequestType.EXPIRED.name().equals(request.getRequestType());
        if (!isLeader && !isOwnPendingRequest)
            throw new AccessDeniedException(
                    "Only the leader of the group, or the assigned member while the request is pending, can delete it");
        task.getProfile().getGroup().ensureNotLocked();
        // Después de los permisos: un ajeno no debe enterarse del tipo ni del estado de la request.
        if (RequestType.MODIFICATION.name().equals(request.getRequestType())
                && RequestStatus.PENDING.name().equals(request.getRequestStatus()))
            throw new ModificationResolvedByEditingException(request.getId());
        this.requestRepository.delete(request);
    }
}
