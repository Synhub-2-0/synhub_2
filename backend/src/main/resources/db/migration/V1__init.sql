-- Esquema inicial de SynHub (AUDIT ARC-04).
-- Generado desde las entidades JPA (Hibernate 7) y revisado a mano: nombres de restricciones legibles e índices
-- para las columnas que se usan en las consultas. Desde aquí, todo cambio de esquema va en una migración nueva
-- (V2__..., V3__...); Hibernate solo valida (spring.jpa.hibernate.ddl-auto=validate).
-- deleted_at: borrado lógico (@SoftDelete, decisión HUM-03). NULL = activo.

-- ---- iam
create table users (
    id         bigint generated by default as identity primary key,
    created_at timestamp(6) with time zone not null,
    updated_at timestamp(6) with time zone not null,
    username   varchar(50)   not null,
    name       varchar(50)   not null,
    surname    varchar(50)   not null,
    email      varchar(255)  not null,
    password   varchar(120)  not null,
    img_url    varchar(1024) not null,
    constraint uk_users_username unique (username),
    constraint uk_users_email unique (email)
);

create table roles (
    id   bigint generated by default as identity primary key,
    name varchar(255) check (name in ('ROLE_USER', 'ROLE_ADMIN')),
    constraint uk_roles_name unique (name)
);

create table user_roles (
    user_id bigint not null,
    role_id bigint not null,
    primary key (role_id, user_id),
    constraint fk_user_roles_user foreign key (user_id) references users,
    constraint fk_user_roles_role foreign key (role_id) references roles
);

-- ---- groups
create table groups (
    id          bigint generated by default as identity primary key,
    created_at  timestamp(6) with time zone not null,
    updated_at  timestamp(6) with time zone not null,
    deleted_at  timestamp(6) with time zone,
    code        varchar(255),
    name        varchar(255) not null,
    description text not null,
    img_url     varchar(255),
    constraint uk_groups_code unique (code)
);

-- Membresía. role_in_group es el ordinal de GroupRole: 0 = GROUP_LEADER, 1 = GROUP_MEMBER.
create table group_profiles (
    id            bigint generated by default as identity primary key,
    created_at    timestamp(6) with time zone not null,
    updated_at    timestamp(6) with time zone not null,
    deleted_at    timestamp(6) with time zone,
    group_id      bigint,
    user_id       bigint,
    role_in_group smallint check (role_in_group between 0 and 1),
    constraint fk_group_profiles_group foreign key (group_id) references groups,
    constraint fk_group_profiles_user foreign key (user_id) references users
);
create index ix_group_profiles_group on group_profiles (group_id);
create index ix_group_profiles_user on group_profiles (user_id);

create table invitations (
    id         bigint generated by default as identity primary key,
    created_at timestamp(6) with time zone not null,
    updated_at timestamp(6) with time zone not null,
    deleted_at timestamp(6) with time zone,
    group_id   bigint,
    member_id  bigint,
    constraint fk_invitations_group foreign key (group_id) references groups,
    constraint fk_invitations_member foreign key (member_id) references users
);
create index ix_invitations_group on invitations (group_id);
create index ix_invitations_member on invitations (member_id);

-- ---- tasks
create table tasks (
    id               bigint generated by default as identity primary key,
    created_at       timestamp(6) with time zone not null,
    updated_at       timestamp(6) with time zone not null,
    deleted_at       timestamp(6) with time zone,
    profile_id       bigint,
    title            varchar(255) not null,
    description      varchar(255) not null,
    due_date         timestamp(6) with time zone not null,
    status           varchar(255) check (status in ('ON_HOLD', 'IN_PROGRESS', 'COMPLETED', 'DONE', 'EXPIRED')),
    times_rearranged integer not null,
    time_passed      bigint not null,
    difficulty       integer,
    context          varchar(255),
    urgency          varchar(255),
    labels           varchar(255),
    ai_accepted      boolean,
    constraint fk_tasks_profile foreign key (profile_id) references group_profiles
);
create index ix_tasks_profile on tasks (profile_id);
-- Para el scheduler de vencimiento: IN_PROGRESS con fecha límite pasada.
create index ix_tasks_status_due_date on tasks (status, due_date);

-- ---- requests
create table requests (
    id             bigint generated by default as identity primary key,
    created_at     timestamp(6) with time zone not null,
    updated_at     timestamp(6) with time zone not null,
    deleted_at     timestamp(6) with time zone,
    task_id        bigint,
    description    varchar(255),
    request_type   varchar(255) check (request_type in ('SUBMISSION', 'MODIFICATION', 'EXPIRED')),
    request_status varchar(255) check (request_status in ('PENDING', 'APPROVED', 'REJECTED')),
    constraint fk_requests_task foreign key (task_id) references tasks
);
create index ix_requests_task on requests (task_id);
