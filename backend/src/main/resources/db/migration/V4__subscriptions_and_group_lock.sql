-- Suscripciones: plan de cada usuario. Sin fila, el usuario está en el plan Gratis.
create table subscriptions (
    id         bigint generated by default as identity primary key,
    created_at timestamp(6) with time zone not null,
    updated_at timestamp(6) with time zone not null,
    deleted_at timestamp(6) with time zone,
    user_id    bigint not null,
    plan       varchar(255) not null check (plan in ('FREE', 'PRO', 'ULTRA')),
    constraint uk_subscriptions_user unique (user_id),
    constraint fk_subscriptions_user foreign key (user_id) references users
);

-- Grupo bloqueado: su líder superó el límite de su plan; es de solo lectura hasta que se active.
alter table groups add column locked boolean not null default false;

-- Los grupos que ya existen respetan el plan Gratis (2 por líder): los más recientes por encima del límite quedan
-- bloqueados y su líder los activa cuando haya cupo. role_in_group 0 = GROUP_LEADER.
update groups set locked = true where id in (
    select group_id from (
        select gp.group_id,
               row_number() over (partition by gp.user_id order by gp.group_id) as position
        from group_profiles gp
        join groups g on g.id = gp.group_id
        where gp.role_in_group = 0 and gp.deleted_at is null and g.deleted_at is null
    ) ranked
    where position > 2
);
